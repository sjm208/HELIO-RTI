def parse_json(raw: str):
    """The JSON object in a reply (fences and surrounding prose ignored), or None."""
    clean = re.sub(r"```(?:json)?|```", "", raw or "").strip()
    try:
        return json.loads(clean)
    except (json.JSONDecodeError, ValueError):
        pass
    a, b = clean.find("{"), clean.rfind("}")
    if a >= 0 and b > a:
        try:
            return json.loads(clean[a:b + 1])
        except (json.JSONDecodeError, ValueError):
            return None
    return None


def detections(data) -> list[dict]:
    return list((data or {}).get("detections", (data or {}).get("features", [])) or [])


def box_pixels(box, w: int, h: int):
    """[ymin, xmin, ymax, xmax] as fractions (or 0–1000, Gemini's habit) to pixels."""
    if not box or len(box) < 4:
        return None
    try:
        yn, xn, yx, xx = (float(v) for v in box[:4])
    except (TypeError, ValueError):
        return None
    if max(yn, xn, yx, xx) > 1:
        yn, xn, yx, xx = yn / 1000, xn / 1000, yx / 1000, xx / 1000
    x0, x1 = sorted((int(xn * w), int(xx * w)))
    y0, y1 = sorted((int(yn * h), int(yx * h)))
    return max(0, x0), max(0, y0), min(w - 1, x1), min(h - 1, y1)


DET_COLOURS = ("#FFD700", "#00FFCC", "#FF6B6B", "#A78BFA", "#34D399",
               "#F97316", "#60A5FA", "#F472B6", "#FACC15", "#4ADE80")


def draw_detections(img, data):
    """The render with each located detection boxed and numbered (RGB uint8)."""
    from PIL import Image, ImageDraw
    arr = np.asarray(img).astype(np.uint8)
    pil = Image.fromarray(arr.copy())
    ih, iw = arr.shape[:2]
    dr = ImageDraw.Draw(pil)
    for i, det in enumerate(detections(data)):
        b = box_pixels(det.get("box_2d") or det.get("bbox"), iw, ih)
        if b is None:
            continue
        x0, y0, x1, y1 = b
        col = DET_COLOURS[i % len(DET_COLOURS)]
        dr.rectangle([x0, y0, x1, y1], outline=col, width=2)
        sev = det.get("severity", "")
        tag = f"{i + 1}. {det.get('label', '?')}" + (f" [{sev}]" if sev else "")
        dr.rectangle([x0, max(0, y0 - 18), x0 + len(tag) * 7 + 6, y0], fill=col)
        dr.text((x0 + 3, max(0, y0 - 16)), tag, fill="black")
    return np.asarray(pil)


def format_report(data: dict) -> str:
    lines = []
    ident = data.get("identification")
    if ident:
        lines.append("══ OBJECT IDENTIFICATION " + "═" * 18)
        lines.append(f"Most likely : {ident.get('most_likely', '—')}")
        for i, a in enumerate(ident.get("alternatives", []), 1):
            lines.append(f"Alternative {i}: {a}")
        if ident.get("evidence"):
            lines.append(f"Evidence    : {ident['evidence']}")
        lines.append("")
    lines.append("══ CONDITION REPORT " + "═" * 22)
    lines.append(f"Object ID : {data.get('artifact_id', '—')}")
    lines.append(f"Material  : {data.get('material_profile', '—')}")
    lines.append(f"Stability : {data.get('stability_rating', '—')} / 5")
    lines.append(f"Priority  : {data.get('conservation_priority', '—')}")
    lines.append("─" * 42)
    for i, d in enumerate(detections(data), 1):
        lines.append(f"\n[{i}] {d.get('label', '?')}  (severity {d.get('severity', '?')}/5)")
        lines.append(f"    {d.get('description', '')}")
    return "\n".join(lines)

def _ssl_context():
    import ssl
    try:
        import certifi
        return ssl.create_default_context(cafile=certifi.where())
    except ImportError:
        return ssl.create_default_context()


def _open(req, timeout, opener):
    """Open *req*; certificate failures stop with the fix, never a retry
    without verification (KD-048)."""
    try:
        if opener is not None:
            return opener(req, timeout)
        if req.full_url.startswith("http://localhost"):
            return urllib.request.urlopen(req, timeout=timeout)
        return urllib.request.urlopen(req, timeout=timeout, context=_ssl_context())
    except urllib.error.HTTPError as exc:
        body = ""
        try:
            body = exc.read().decode("utf-8", "replace")
        except Exception:
            pass
        if exc.code == 429 and "generativelanguage" in req.full_url:
            raise RuntimeError(
                "Rate limit reached.\n\nYou are on the Gemini free tier (limited requests per "
                "minute and per day).\nVisit aistudio.google.com to add billing and remove the "
                f"limit.\n\n(HTTP 429 — {exc.reason})") from None
        detail = ""
        try:
            j = json.loads(body)
            detail = (j.get("error", {}) or {}).get("message", "") if isinstance(j.get("error"), dict) \
                else str(j.get("error", ""))
        except Exception:
            detail = body[:300]
        raise RuntimeError(f"The provider answered HTTP {exc.code} ({exc.reason})."
                           + (f"\n\n{detail}" if detail else "")) from None
    except urllib.error.URLError as exc:
        text = str(exc)
        if "CERTIFICATE_VERIFY_FAILED" in text or "certificate verify failed" in text:
            raise RuntimeError(
                "The provider's security certificate could not be checked, so nothing was sent.\n\n"
                "On macOS run 'Install Certificates.command' in the Python folder in "
                "Applications, or: pip install certifi") from None
        if req.full_url.startswith("http://localhost"):
            raise RuntimeError(
                "No local model server answered at " + req.full_url.split("/v1")[0].split("/api")[0]
                + ".\n\nStart Ollama or LM Studio's server, with a model loaded.") from None
        raise


def list_local_models(vendor: str, *, opener=None, timeout: float = 3.0) -> list[str]:
    """The models a local server has loaded (empty if none answers)."""
    v = VENDORS.get(vendor, {})
    if not v.get("local"):
        return []
    try:
        resp = _open(urllib.request.Request(v["models_url"]), timeout, opener)
        data = json.loads(resp.read().decode())
    except Exception:
        return []
    if v["kind"] == "ollama":
        return [m.get("name", "") for m in data.get("models", []) if m.get("name")]
    return [m.get("id", "") for m in data.get("data", []) if m.get("id")]


def request_for(vendor: str, key: str, prompt: str, image_b64: str | None = None,
                max_tokens: int = 1024, model: str | None = None) -> urllib.request.Request:
    """The HTTP request each provider expects (no network)."""
    if vendor not in VENDORS:
        raise ValueError(f"Unknown vendor: {vendor}")
    v = VENDORS[vendor]
    model = (model or v["model"]).strip()
    if not v["local"] and not key:
        raise ValueError(f"No API key entered for {vendor}.\n"
                         "Enter your key in the AI settings, or choose a model on this computer.")
    if v["local"] and not model:
        raise ValueError(f"Choose which model {vendor.split(' (')[0]} should use.")
    if not v["vision"]:
        image_b64 = None
    kind = v["kind"]
    headers = {"content-type": "application/json"}
    if kind == "anthropic":
        content = []
        if image_b64:
            content.append({"type": "image", "source": {"type": "base64", "media_type": "image/jpeg",
                                                        "data": image_b64}})
        content.append({"type": "text", "text": prompt})
        body = {"model": model, "max_tokens": max_tokens,
                "messages": [{"role": "user", "content": content}]}
        headers.update({"x-api-key": key, "anthropic-version": "2023-06-01"})
        url = v["url"]
    elif kind == "gemini":
        parts = []
        if image_b64:
            parts.append({"inline_data": {"mime_type": "image/jpeg", "data": image_b64}})
        parts.append({"text": prompt})
        body = {"contents": [{"parts": parts}], "generationConfig": {"maxOutputTokens": max_tokens}}
        headers["x-goog-api-key"] = key           # not ?key= in the URL, where logs keep it
        url = v["url"].format(model=model)
    elif kind == "ollama":
        msg = {"role": "user", "content": prompt}
        if image_b64:
            msg["images"] = [image_b64]
        body = {"model": model, "messages": [msg], "stream": False,
                "options": {"num_predict": max_tokens}}
        url = v["url"]
    else:                                          # OpenAI-compatible: OpenAI, Mistral, LM Studio
        if image_b64:
            content = [{"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image_b64}",
                                                            "detail": "high"}},
                       {"type": "text", "text": prompt}]
        else:
            content = prompt
        body = {"model": model, "max_tokens": max_tokens,
                "messages": [{"role": "user", "content": content}]}
        if key:
            headers["Authorization"] = f"Bearer {key}"
        url = v["url"]
    return urllib.request.Request(url, data=json.dumps(body).encode(), headers=headers)


def read_reply(vendor: str, data: dict) -> str:
    kind = VENDORS[vendor]["kind"]
    if kind == "anthropic":
        text = "".join(b.get("text", "") for b in data.get("content", []) if b.get("type") == "text")
        if not text:
            raise RuntimeError(f"Unexpected reply:\n{json.dumps(data, indent=2)[:500]}")
        return text
    if kind == "gemini":
        fb = data.get("promptFeedback", {})
        if fb.get("blockReason"):
            raise RuntimeError(f"Gemini blocked the request: {fb['blockReason']}\n"
                               "Try a different render engine output or rephrase the prompt.")
        try:
            return "".join(p.get("text", "") for p in data["candidates"][0]["content"]["parts"])
        except (KeyError, IndexError):
            raise RuntimeError(
                f"Unexpected Gemini response structure:\n{json.dumps(data, indent=2)[:500]}") from None
    if kind == "ollama":
        try:
            return data["message"]["content"]
        except KeyError:
            raise RuntimeError(f"Unexpected reply:\n{json.dumps(data, indent=2)[:500]}") from None
    try:
        return data["choices"][0]["message"]["content"]
    except (KeyError, IndexError):
        raise RuntimeError(f"Unexpected reply:\n{json.dumps(data, indent=2)[:500]}") from None


def call(vendor: str, key: str, prompt: str, image_b64: str | None = None, max_tokens: int = 1024,
         *, model: str | None = None, timeout: float = 120.0, opener: Callable | None = None) -> str:
    """Ask *vendor*; returns the reply's text or raises with a readable message.
    *opener(request, timeout)* replaces the network (tests)."""
    req = request_for(vendor, key, prompt, image_b64, max_tokens, model)
    resp = _open(req, timeout, opener)
    return read_reply(vendor, json.loads(resp.read().decode()))



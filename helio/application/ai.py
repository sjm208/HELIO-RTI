"""AI descriptions of the render, GUI-free (the classic AI Tools tab).

One dispatcher for the cloud providers HELIO 2 offered and two local ones,
the prompts it used, and the parsing and drawing of what comes back.  Both
apps call these, so they ask the same questions and read the answers the
same way.  What a language model says about an object is a suggestion to
check, never a measurement: every result carries CAVEAT.

Changed from HELIO 2:

* a certificate error was retried with verification switched off, which
  would send the API key to anyone able to intercept the connection; it now
  stops and says how to fix the certificates (KD-048);
* the Gemini key travelled in the URL (and so into proxy and server logs);
  it goes in the x-goog-api-key header;
* the Claude model ID had been retired; each provider's model can be set;
* Ollama and LM Studio run a model on this computer: nothing leaves it and
  no key is needed;
* the surface statistics given to the model are areal ISO 25178 parameters
  of the levelled surface (Sa, Sq, Ssk, Sku, Sz), with their unit; HELIO 2
  sent profile names (Ra, Rq, Rsk) for statistics of the unlevelled depth,
  so a tilt read as roughness (KD-049).
"""

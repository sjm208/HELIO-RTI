def image_b64(img, max_side: int = 1024, quality: int = 85) -> str:
    """The render as a JPEG, longest side at most *max_side*, base64."""
    import base64
    import io
    from PIL import Image
    pil = Image.fromarray(np.asarray(img).astype(np.uint8))
    w, h = pil.size
    s = min(max_side / max(w, h), 1.0)
    if s < 1.0:
        pil = pil.resize((max(1, int(w * s)), max(1, int(h * s))), Image.BILINEAR)
    buf = io.BytesIO()
    pil.convert("RGB").save(buf, format="JPEG", quality=quality)
    return base64.b64encode(buf.getvalue()).decode()


def surface_stats(depth, z_mm_per_unit=None) -> dict:
    """ISO 25178 areal parameters of the plane-levelled surface: Sa, Sq,
    Ssk, Sku, Sz, in µm with a height scale, else relative units."""
    d = np.asarray(depth, np.float64)
    h, w = d.shape
    yy, xx = np.mgrid[0:h, 0:w]
    A = np.column_stack([xx.ravel(), yy.ravel(), np.ones(h * w)])
    step = max(1, (h * w) // 200_000)
    coef, *_ = np.linalg.lstsq(A[::step], d.ravel()[::step], rcond=None)
    r = d.ravel() - A @ coef
    r -= r.mean()
    sq = float(np.sqrt(np.mean(r ** 2)))
    k = z_mm_per_unit * 1000.0 if z_mm_per_unit else 1.0
    return {"Sa": float(np.mean(np.abs(r))) * k, "Sq": sq * k,
            "Ssk": float(np.mean(r ** 3) / (sq ** 3 + 1e-12)),
            "Sku": float(np.mean(r ** 4) / (sq ** 4 + 1e-12)),
            "Sz": float(r.max() - r.min()) * k,
            "unit": "µm" if z_mm_per_unit else "px of height"}


def _stats_line(st: dict, full: bool = False) -> str:
    u = st["unit"]
    s = f"Sa={st['Sa']:.5g} Sq={st['Sq']:.5g} {u}"
    if full:
        s += f"  Ssk={st['Ssk']:.3f}  Sku={st['Sku']:.3f}  Sz={st['Sz']:.5g} {u}"
    return s


